"""Use case: verify an existing data directory (SPEC 5.1 `verify`, SPEC_DECISIONS 43.2).

Two stages. First the checksums and every invariant of SPEC 5.8, on the files as they are.
Then conformance: the data set is regenerated in memory from the manifest's `seed` and
`profile`, and every file on disk, the manifest, the reference data and the answer key
included, must be byte identical to the regenerated one. A data set written by another
generator version cannot be regenerated, so that is said in one sentence instead.
"""

from __future__ import annotations

import hashlib
import re
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from pathlib import Path

from onepledge_datagen import GENERATOR_VERSION
from onepledge_datagen.application.example_contract import expected_document
from onepledge_datagen.application.invariants import InvariantChecker
from onepledge_datagen.application.model import (
    CHECKSUMS,
    EXAMPLE_EXPECTED,
    EXAMPLE_RECORDS,
    EXAMPLE_TAPE,
    MANIFEST,
)
from onepledge_datagen.application.ports import DataSetCodec, DataSetDirectory
from onepledge_datagen.application.view import DataSetView
from onepledge_datagen.domain.bounded_json import parse_bounded_json
from onepledge_datagen.domain.entities import Profile
from onepledge_datagen.domain.errors import DataSetUnreadableError, GeneratorVersionError
from onepledge_datagen.domain.oracle.model import RowObservation
from onepledge_datagen.domain.text import plain_list
from onepledge_datagen.domain.text_values import MAX_INTEGER

PROFILE_VALUES = tuple(profile.value for profile in Profile)
_PLAIN_VERSION = re.compile(r"^[0-9A-Za-z.+-]{1,32}$")


@dataclass(frozen=True)
class VerificationReport:
    """The outcome of `verify`."""

    violations: tuple[str, ...]
    files: int
    rows_checked: int

    @property
    def ok(self) -> bool:
        """Whether nothing was violated."""
        return not self.violations


def checksum_violations(files: dict[str, bytes]) -> list[str]:
    """Every file must be listed with its SHA-256, and nothing else may be present."""
    if CHECKSUMS not in files:
        return [f"{CHECKSUMS} is missing"]
    try:
        document = parse_bounded_json(files[CHECKSUMS], CHECKSUMS)
    except DataSetUnreadableError as error:
        return [error.sentence.removesuffix(".")]
    listed = document.get("files") if isinstance(document, dict) else None
    if not isinstance(listed, dict) or not all(isinstance(value, str) for value in listed.values()):
        return [f"{CHECKSUMS} has no files object of path to SHA-256 text"]
    violations = []
    others = {path for path in files if path != CHECKSUMS}
    for path in sorted(set(listed) | others):
        if path not in files:
            violations.append(f"{path} is listed in {CHECKSUMS} but missing")
        elif path not in listed:
            violations.append(f"{path} is present but not listed in {CHECKSUMS}")
        elif hashlib.sha256(files[path]).hexdigest() != listed[path]:
            violations.append(f"{path} does not match its checksum")
    return violations


type Regenerate = Callable[[int, Profile], Mapping[str, bytes]]


def manifest_origin(files: Mapping[str, bytes]) -> tuple[object, object, object]:
    """The `generator_version`, `seed` and `profile` values of manifest.json, None where absent."""
    try:
        manifest = parse_bounded_json(files.get(MANIFEST, b""), MANIFEST)
    except DataSetUnreadableError:
        return None, None, None
    if not isinstance(manifest, dict):
        return None, None, None
    return manifest.get("generator_version"), manifest.get("seed"), manifest.get("profile")


def check_generator_version(version: object) -> None:
    """A data set of another generator version cannot be regenerated by this one: one sentence."""
    if version is not None and version != GENERATOR_VERSION:
        shown = version if isinstance(version, str) and _PLAIN_VERSION.fullmatch(version) else "another"
        raise GeneratorVersionError(
            f"manifest.json was written by generator version {shown} and this is version "
            f"{GENERATOR_VERSION}, which cannot regenerate it; verify it with the generator that wrote it."
        )


def regeneration_violations(
    files: Mapping[str, bytes], seed: object, profile: object, regenerate: Regenerate
) -> list[str]:
    """Every file that differs from, is missing from or is extra to what the seed and profile generate."""
    problems = []
    valid_seed = isinstance(seed, int) and not isinstance(seed, bool) and 0 <= seed <= MAX_INTEGER
    if not valid_seed:
        problems.append(
            f"manifest.json has no valid seed: a whole number from 0 to {MAX_INTEGER:,} is required"
        )
    if profile not in PROFILE_VALUES:
        problems.append(
            f"manifest.json has no valid profile: one of {plain_list(PROFILE_VALUES)} is required"
        )
    if problems or not isinstance(seed, int) or not isinstance(profile, str):
        return problems
    expected = regenerate(seed, Profile(profile))
    origin = f"seed {seed}, profile {profile}"
    for path in sorted(set(files) | set(expected)):
        if path not in files:
            problems.append(f"{path} is missing; {origin} generates it")
        elif path not in expected:
            problems.append(f"{path} is not part of what {origin} generates")
        elif files[path] != expected[path]:
            problems.append(f"{path} differs from what {origin} generates")
    return problems


class VerifyDataSet:
    """Reads a data directory, re-checks checksums and every invariant, then regenerates and compares."""

    def __init__(
        self,
        codec: DataSetCodec,
        directory: DataSetDirectory,
        checker: InvariantChecker,
        regenerate: Regenerate,
    ) -> None:
        self._codec = codec
        self._directory = directory
        self._checker = checker
        self._regenerate = regenerate

    def run(self, source: Path) -> VerificationReport:
        """All violations found; an unreadable directory raises DataSetUnreadableError."""
        files = self._directory.read(source)
        version, seed, profile = manifest_origin(files)
        check_generator_version(version)
        violations = checksum_violations(files)
        view = self._codec.parse(files)
        report = self._checker.check(view)
        violations.extend(report.violations)
        if EXAMPLE_EXPECTED in files:
            violations.extend(self._example_violations(files, view, report.observations))
        violations.extend(regeneration_violations(files, seed, profile, self._regenerate))
        return VerificationReport(tuple(violations), len(files), report.rows_checked)

    def _example_violations(
        self, files: dict[str, bytes], view: DataSetView, observations: dict[tuple[str, int], RowObservation]
    ) -> list[str]:
        violations = []
        tape = files.get(view.steps[0].file)
        if files.get(EXAMPLE_TAPE) != tape:
            violations.append(f"{EXAMPLE_TAPE} differs from the generated tape")
        for source, target in EXAMPLE_RECORDS.items():
            if files.get(target) != files.get(source):
                violations.append(f"{target} differs from {source}")
        expected = self._codec.render_json(expected_document(view, observations))
        if files.get(EXAMPLE_EXPECTED) != expected:
            violations.append(f"{EXAMPLE_EXPECTED} differs from the results of the oracle")
        return violations
